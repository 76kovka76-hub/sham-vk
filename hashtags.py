def create_tags(scene, history, slot):
    """Детерминированная ротация при неизменной истории, без повторения троек."""
    all_history = [p.get("hashtags", []) for p in history.get("posts", [])]
    previous_sets = {tuple(sorted(x)) for x in all_history if len(x) == 3}
    recent = {tag for item in all_history[-12:] for tag in item}
    counts = Counter(tag for item in all_history for tag in item)
    scene_pool = list(dict.fromkeys(SCENES.get(scene, SCENES["life"])))
    general_pool = [x for x in dict.fromkeys(GENERAL) if x not in scene_pool]
    rng = random.Random(hashlib.sha256(slot.encode("utf-8")).hexdigest())
    # Start with least-used tags; randomize ties for variety.
    def order(tags):
        return sorted(tags, key=lambda tag: (tag in recent, counts[tag], rng.random()))
    themed = order(scene_pool)
    generic = order(general_pool)
    for t in themed:
        for a in generic[:65]:
            for b in generic[:65]:
                if a == b or a == t or b == t:
                    continue
                chosen = [t, a, b]
                if tuple(sorted(chosen)) in previous_sets:
                    continue
                # Prefer not to repeat even a single hashtag in the 12 newest posts.
                if any(x in recent for x in chosen):
                    continue
                return chosen
    # When all recent options are depleted, prioritize triple uniqueness.
    for t in themed:
        for a in generic:
            for b in generic:
                if len({t, a, b}) != 3:
                    continue
                chosen = [t, a, b]
                if tuple(sorted(chosen)) not in previous_sets:
                    return chosen
    raise RuntimeError("Не удалось собрать 3 уникальных хэштега")


def add_hashtags(caption, tags):
    if len(tags) != 3 or len(set(tags)) != 3:
        raise ValueError("Every post must contain exactly three different tags")
    if not all(re.fullmatch(r"#[A-Za-zА-Яа-яЁё0-9_]+", tag) for tag in tags):
        raise ValueError("Invalid hashtag")
    return caption.strip() + "\n\n" + " ".join(tags)
